import { mkdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { DeleteObjectsCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3'
import { env } from '../config/env.js'
import { AppError } from './errors.js'

/*
 * Where uploaded photos are stored.
 *
 *   r2     Cloudflare R2 (production, and development once the R2_* settings are filled in).
 *          Public URL: MEDIA_BASE_URL/<key>  (e.g. https://media.mpfsl.lk/media/2026/10/abc/large.webp)
 *   local  Development only: files on disk in LOCAL_UPLOADS_DIR, served by the API at /api/uploads/<key>
 *          (app.js mounts that route only for this driver).
 *   none   Production without R2: uploads are refused with STORAGE_NOT_CONFIGURED.
 *
 * Each Media document remembers which driver stored it, so switching drivers in development doesn't
 * break the URLs of photos uploaded earlier.
 */

const IMMUTABLE = 'public, max-age=31536000, immutable' // keys are never reused, so cache forever

const serverDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..')
export const localUploadsDir = path.resolve(serverDir, env.LOCAL_UPLOADS_DIR)
export const LOCAL_URL_PREFIX = '/api/uploads'

let r2Client = null
const r2 = () =>
  (r2Client ??= new S3Client({
    region: 'auto',
    endpoint: `https://${env.R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
    credentials: { accessKeyId: env.R2_ACCESS_KEY_ID, secretAccessKey: env.R2_SECRET_ACCESS_KEY },
  }))

const drivers = {
  r2: {
    async put(key, body, contentType) {
      await r2().send(
        new PutObjectCommand({ Bucket: env.R2_BUCKET, Key: key, Body: body, ContentType: contentType, CacheControl: IMMUTABLE }),
      )
    },
    async remove(keys) {
      if (!keys.length) return
      await r2().send(
        new DeleteObjectsCommand({ Bucket: env.R2_BUCKET, Delete: { Objects: keys.map((Key) => ({ Key })), Quiet: true } }),
      )
    },
    url: (key) => `${env.MEDIA_BASE_URL.replace(/\/$/, '')}/${key}`,
  },

  local: {
    async put(key, body) {
      const file = safeLocalPath(key)
      await mkdir(path.dirname(file), { recursive: true })
      await writeFile(file, body)
    },
    async remove(keys) {
      await Promise.all(keys.map((key) => rm(safeLocalPath(key), { force: true })))
    },
    url: (key) => `${LOCAL_URL_PREFIX}/${key}`,
  },

  none: {
    async put() {
      throw new AppError(503, 'STORAGE_NOT_CONFIGURED', 'Photo uploads are turned off until photo storage (R2) is set up')
    },
    async remove() {},
    url: (key) => key,
  },
}

// Keys are generated by us, but never let one escape the uploads folder.
function safeLocalPath(key) {
  const file = path.resolve(localUploadsDir, key)
  if (!file.startsWith(localUploadsDir + path.sep)) throw new Error(`Invalid storage key: ${key}`)
  return file
}

/** The driver new uploads go to ('r2', 'local' or 'none'). */
export const currentDriver = env.STORAGE_DRIVER

/** Stores a file with the current driver. */
export const putObject = (key, body, contentType) => drivers[currentDriver].put(key, body, contentType)

/** Deletes files that were stored with `driver` (defaults to the current one). */
export const removeObjects = (keys, driver = currentDriver) => drivers[driver].remove(keys)

/** Public URL of a file that was stored with `driver`. */
export const publicUrl = (key, driver = currentDriver) => drivers[driver].url(key)
